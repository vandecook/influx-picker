@pytest.mark.parametrize(
    ("entity_id", "state", "attributes", "options", "expected"), CASES
)
def test_golden(entity_id, state, attributes, options, expected) -> None:
    """The point serializes to exactly the expected line."""
    point = state_to_point(entity_id, state, attributes, T, options)
    assert point is not None
    assert to_line(point) == expected


def test_heartbeat_field() -> None:
    """Heartbeat points carry `_heartbeat=true`; change points do not."""
    attrs = {"friendly_name": "Counter"}
    change = state_to_point("sensor.counter", "42", attrs, T, SchemaOptions())
    beat = state_to_point(
        "sensor.counter", "42", attrs, T, SchemaOptions(), heartbeat=True
    )
    assert "_heartbeat" not in to_line(change)
    assert to_line(beat) == (
        "sensor.counter,domain=sensor,entity_id=counter "
        f'_heartbeat=true,friendly_name_str="Counter",value=42 {TS}'
    )


def test_startup_field() -> None:
    """Startup snapshot points (option "last_updated") carry `_startup=true`."""
    attrs = {"friendly_name": "Counter"}
    point = state_to_point(
        "sensor.counter", "42", attrs, T, SchemaOptions(), startup=True
    )
    assert to_line(point) == (
        "sensor.counter,domain=sensor,entity_id=counter "
        f'_startup=true,friendly_name_str="Counter",value=42 {TS}'
    )


@pytest.mark.parametrize("state", ["unknown", "unavailable", "", None])
def test_skipped_states(state) -> None:
    """These states are never written."""
    assert state_to_point("sensor.x", state, {}, T, SchemaOptions()) is None


@pytest.mark.parametrize(
    ("precision", "expected"),
    [
        ("s", "1794916800"),
        ("ms", "1794916800123"),
        ("us", "1794916800123456"),
        ("ns", TS),
    ],
)
def test_precision(precision, expected) -> None:
    """Timestamps are truncated to the precision."""
    point = state_to_point("sensor.counter", "42", {}, T, SchemaOptions())
    assert to_line(point, precision).endswith(f" {expected}")


def test_schema_options_from_defaults() -> None:
    """Empty stored options give the core defaults."""
    assert schema_options_from({}) == SchemaOptions()


def test_schema_options_from_full() -> None:
    """Stored options (as the flows save them) convert to SchemaOptions."""
    options = schema_options_from(
        {
            "measurement_attr": "entity_id",
            "default_measurement": "units",
            "override_measurement": "",
            "tags": {"source": "HA"},
            "tags_attributes": ["friendly_name"],
            "ignore_attributes": ["icon"],
            "component_config": {"sensor.a": {"override_measurement": "m"}},
            "component_config_domain": {"light": {"ignore_attributes": ["x"]}},
            "component_config_glob": {"sensor.*": None},
        }
    )
    assert options == SchemaOptions(
        measurement_attr="entity_id",
        default_measurement="units",
        override_measurement=None,
        tags={"source": "HA"},
        tags_attributes=["friendly_name"],
        ignore_attributes=["icon"],
        component_config={"sensor.a": EntityCustomization(override_measurement="m")},
        component_config_domain={"light": EntityCustomization(ignore_attributes=["x"])},
        component_config_glob={"sensor.*": EntityCustomization()},
    )


